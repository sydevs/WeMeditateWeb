import type { BuildResult, Inventory, NewSite, OldRecord, OldUrl, UrlClass } from './build'

const CLASSES: [UrlClass, string][] = [
  ['live', 'already a live page (no redirect)'],
  ['exact', "matching page, in the old address's language"],
  ['english-untranslated', 'matching page, English (launch language, page not published in it)'],
  ['english-unsupported-locale', 'matching page, English (language not launching)'],
  ['section', 'no matching page, nearest section'],
  ['fixed-page', 'fixed route, its own page'],
  ['fixed-section', 'fixed route, the nearest section'],
  ['fixed-home', 'fixed route, home page'],
]

const TYPE_LABEL: Record<string, string> = {
  article: 'article',
  event: 'article (event, root path)',
  category: 'category',
  meditation: 'meditation',
  treatment: 'technique',
  subtle: 'subtle system',
  stream: 'live stream',
  promo: 'promo page (root path)',
  fixed: 'fixed route',
}

function table(headers: string[], rows: (string | number)[][]): string {
  const line = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`

  return [line(headers), line(headers.map(() => '---')), ...rows.map(line)].join('\n')
}

function tally(urls: OldUrl[], key: (url: OldUrl) => string): Map<string, Map<UrlClass, number>> {
  const out = new Map<string, Map<UrlClass, number>>()

  for (const url of urls) {
    const bucket = out.get(key(url)) ?? new Map<UrlClass, number>()

    bucket.set(url.class, (bucket.get(url.class) ?? 0) + 1)
    out.set(key(url), bucket)
  }

  return out
}

function matrix(
  urls: OldUrl[],
  key: (url: OldUrl) => string,
  order: string[],
  label: (k: string) => string,
): string {
  const counts = tally(urls, key)
  const used = CLASSES.filter(([cls]) => urls.some((url) => url.class === cls))
  const rows = order
    .filter((k) => counts.has(k))
    .map((k) => {
      const bucket = counts.get(k)!
      const total = [...bucket.values()].reduce((a, b) => a + b, 0)

      return [label(k), ...used.map(([cls]) => bucket.get(cls) ?? 0), total]
    })
  const totals = used.map(([cls]) => urls.filter((url) => url.class === cls).length)

  rows.push(['**all**', ...totals, urls.length])

  return table(['', ...used.map(([, text]) => text), 'total'], rows)
}

const describe = (record: OldRecord): string => {
  const english = record.rows.find((row) => row.locale === 'en') ?? record.rows[0]

  return `${record.type} ${record.id} \`${english.slug}\`${english.name ? ` "${english.name.trim()}"` : ''}`
}

export function renderCoverage(result: BuildResult, inventory: Inventory, site: NewSite): string {
  const { urls, records } = result
  const out: string[] = []
  const redirected = urls.filter((url) => url.target !== null)
  const served = (flag: boolean) => urls.filter((url) => url.served === flag).length

  out.push(
    '# Legacy redirect coverage',
    '',
    'Generated by `pnpm redirects:generate`. Do not edit by hand.',
    '',
    `Old-site inventory exported ${inventory.exportedOn}; new-site snapshot fetched ${site.fetchedOn} (${site.pages.length} pages, ${site.meditations.length} meditations).`,
    '',
    '## Summary',
    '',
    `- ${urls.length} old addresses enumerated from the records (${served(true)} the old site answered or 301ed when exported, ${served(false)} it did not: archived, unpublished or scheduled records, languages it sent to its maintenance page, and the \`/articles/category/<slug>\` route, which has no controller action. All are kept so a link to them still lands somewhere).`,
    `- ${redirected.length} of them redirect. ${urls.length - redirected.length} already are a live page on the new site, so the lookup returns \`null\` for them.`,
    `- The map holds ${Object.values(result.map.exact).reduce((n, byLocale) => n + Object.values(byLocale).reduce((m, slugs) => m + Object.keys(slugs).length, 0), 0)} exact slugs and ${Object.keys(result.map.pages).length} pages. Fixed routes cost no entry of their own.`,
    '',
    '## By kind of address',
    '',
    matrix(
      urls,
      (url) => url.type,
      Object.keys(TYPE_LABEL),
      (k) => TYPE_LABEL[k],
    ),
    '',
    '## By old language',
    '',
    matrix(
      urls,
      (url) => url.locale,
      [...new Set(urls.map((url) => url.locale))].sort(),
      (k) => `\`${k}\``,
    ),
    '',
  )

  out.push(
    '## Fixed routes',
    '',
    table(
      ['route key', 'lands on', 'how'],
      Object.entries(result.roleResolution).map(([key, value]) => {
        const [slug] = result.map.pages[String(value.target)] ?? ['?']

        return [`\`${key}\``, `\`/${slug}\``, value.how]
      }),
    ),
    '',
  )

  const byType = new Map<string, OldRecord[]>()

  for (const record of records)
    (byType.get(record.type) ?? byType.set(record.type, []).get(record.type)!).push(record)

  out.push('## How records matched', '')
  out.push(
    table(
      [
        'kind',
        'records',
        'by slug',
        'by slug history',
        'by title',
        'curated',
        'other-language slug',
        'ambiguous',
        'no match',
      ],
      [...byType].map(([type, list]) => {
        const count = (how: string) =>
          list.filter((r) => r.match.kind === 'match' && r.match.how === how).length

        return [
          type,
          list.length,
          count('slug'),
          count('history'),
          count('title'),
          count('curated'),
          count('other-locale slug'),
          list.filter((r) => r.match.kind === 'ambiguous').length,
          list.filter((r) => r.match.kind === 'none').length,
        ]
      }),
    ),
    '',
  )

  const matched = records.filter((r) => r.match.kind === 'match' && r.type !== 'static')

  out.push(
    '### Matches that were not an exact slug',
    '',
    'Review these: a title or history match is a judgement.',
    '',
  )

  const soft = matched.filter((r) => r.match.kind === 'match' && r.match.how !== 'slug')

  out.push(
    ...(soft.length
      ? soft.map(
          (r) =>
            `- ${describe(r)} → page ${(r.match as { target: number }).target} (${(r.match as { how: string }).how})`,
        )
      : ['None.']),
    '',
    '### Ambiguous matches (no redirect to a page; the section takes them)',
    '',
  )

  const ambiguous = records.filter((r) => r.match.kind === 'ambiguous')

  out.push(
    ...(ambiguous.length
      ? ambiguous.map(
          (r) =>
            `- ${describe(r)}: pages ${(r.match as { candidates: number[] }).candidates.join(', ')}`,
        )
      : ['None.']),
    '',
    '### Address conflicts',
    '',
    ...(result.conflicts.length ? result.conflicts.map((c) => `- ${c}`) : ['None.']),
    '',
  )

  const sectionRecords = records.filter((r) => r.type !== 'static' && r.match.kind !== 'match')
  const urlCount = (record: OldRecord) =>
    urls.filter((url) => url.record === `${record.type} ${record.id}`).length

  out.push(
    '## Section fallbacks',
    '',
    'Records with no matching page. Every old address of these goes to its nearest section.',
    '',
  )

  for (const type of [
    'article',
    'category',
    'meditation',
    'treatment',
    'subtle',
    'stream',
    'promo',
  ]) {
    const list = sectionRecords.filter((r) => r.type === type)

    if (!list.length) continue

    const live = list.filter((r) =>
      r.rows.some((row) =>
        urls.some((u) => u.record === `${r.type} ${r.id}` && u.served && u.locale === row.locale),
      ),
    )

    out.push(
      `### ${TYPE_LABEL[type]} (${list.length} records, ${live.length} answered by the old site)`,
      '',
      ...(type === 'meditation'
        ? [
            `The old site's meditations are videos; the new site's ${site.meditations.length} are audio. These ${list.length} have no single new meditation with the same title, and go to the Meditate Now page.`,
            '',
          ]
        : list.map(
            (r) =>
              `- ${describe(r)}, ${r.rows.length} language${r.rows.length === 1 ? '' : 's'}, ${urlCount(r)} addresses${live.includes(r) ? '' : ', not live'}`,
          )),
      '',
    )
  }

  const launch = ['ru', 'it', 'es', 'fr', 'de', 'pt-BR', 'cs', 'uk', 'bg']
  const shells = site.pages
    .map((page) => ({
      slug: page.slug,
      locales: launch.filter((l) => page.published.includes(l) && !page.translated.includes(l)),
    }))
    .filter((page) => page.locales.length > 0)

  out.push(
    '## Pages treated as not published in a language',
    '',
    'SahajCloud flags these published in the language, but they have no title there: an untranslated shell that renders the English text. A redirect treats the language as not having the page, and lands on the English one.',
    '',
    ...(shells.length
      ? shells.map((page) => `- \`/${page.slug}\`: ${page.locales.join(', ')}`)
      : ['None.']),
    '',
    '## Could not be determined',
    '',
    `- ${result.recordsWithoutEnglish.length} records have no published English translation in the inventory, so only a slug in another language could match them: ${result.recordsWithoutEnglish.map((r) => `${r.type} ${r.id}`).join(', ') || 'none'}.`,
    '- Rows that were never published (draft or in progress) are not exported, so a link to one cannot be redirected.',
    '',
    '## Self-check',
    '',
    result.violations.length
      ? result.violations.map((v) => `- ${v}`).join('\n')
      : `Every one of the ${urls.length} addresses above, percent-encoded, returns its expected target from \`lookupLegacyRedirect\`, and no target is itself redirected.`,
    '',
  )

  return out.join('\n')
}
